local source = debug.getinfo(1, "S").source
local dir = source:sub(2):match("^(.*)[/\\]") or "."
dofile(dir .. "/../../FrameWork/setup_paths.lua")
local gui = require("gui")
local width, height = gui.ScreenSizeGet()
assert(width, height)
local taskbar, taskbarError = gui.TaskbarHeightGet()
assert(gui.WindowClient("Screen, Label, and Font", 480, 300, "fixed", "bottom-left"))
assert(gui.DefaultFontSet("Segoe UI", 11))
assert(gui.Label("heading", "Center alignment", 20, 15, 440, 48, "center", "center"))
assert(gui.FontSet("heading", "Segoe UI", 12, "bold", "italic"))
assert(gui.Label("screen", "Screen: " .. width .. " x " .. height .. " px", 20, 75, 440, 25, "right"))
local info = taskbar ~= nil and ("Taskbar: " .. taskbar .. " px") or taskbarError
assert(gui.Label("taskbar", info, 20, 108, 440, 55))
assert(gui.Button("small", "12 items", 20, 185, 130, 36))
assert(gui.Button("large", "18 items", 170, 185, 130, 36))
assert(gui.Button("close", "Close", 320, 185, 140, 36))
assert(gui.OnClick("small", function() assert(gui.FontSizeSet("heading", 12)) end))
assert(gui.OnClick("large", function() assert(gui.FontSizeSet("heading", 18)) end))
assert(gui.OnClick("close", function() assert(gui.Close()) end))
assert(gui.Button("red", "Red", 20, 235, 130, 36))
assert(gui.Button("blue", "Blue", 170, 235, 130, 36))
assert(gui.Button("system", "System", 320, 235, 140, 36))
assert(gui.OnClick("red", function() assert(gui.TextColorSet("heading", "Red")) end))
assert(gui.OnClick("blue", function() assert(gui.TextColorSet("heading", "Blue")) end))
assert(gui.OnClick("system", function() assert(gui.TextColorSet("heading", nil)) end))
gui.Run()
