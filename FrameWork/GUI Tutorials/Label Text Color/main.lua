local script = debug.getinfo(1, "S").source:sub(2)
local dir = script:match("^(.*)[/\\]") or "."
dofile(dir .. "/../../FrameWork/setup_paths.lua")
-- Use a color name such as "Red", a number in 0xRRGGBB format, or three RGB values.
local gui = require("gui")
assert(gui.WindowClient("Label Text Color", 480, 250, "fixed", "center"))
assert(gui.DefaultFontSet("Segoe UI", 11))
assert(gui.Label("label1", "Colored labels", 20, 18, 440, 32))
assert(gui.FontSet("label1", "Segoe UI", 16, "bold"))
assert(gui.TextColorSet("label1", "Blue"))
assert(gui.Label("label2", "Use a color name, one number, or three RGB values.", 20, 62, 440, 26))
assert(gui.TextColorSet("label2", 0x6E6E6E))
assert(gui.Label("label3", "Initial color set with three RGB values", 20, 108, 440, 30))
assert(gui.TextColorSet("label3", 30, 90, 180))
assert(gui.Button("button1", "Green", 20, 170, 130, 32))
assert(gui.Button("button2", "Red", 165, 170, 130, 32))
assert(gui.Button("button3", "Default", 310, 170, 150, 32))
assert(gui.OnClick("button1", function()
    assert(gui.TextSet("label3", "Text color changed to green"))
    assert(gui.TextColorSet("label3", "Green"))
end))
assert(gui.OnClick("button2", function()
    assert(gui.TextSet("label3", "Error message"))
    assert(gui.TextColorSet("label3", 0xB42828))
end))
assert(gui.OnClick("button3", function()
    assert(gui.TextSet("label3", "System text color"))
    assert(gui.TextColorSet("label3", nil))
end))
assert(gui.Run())
